#!/usr/bin/env python3
"""Barrens Front influence: war boards as NPCs (with quest markers), Rally Masters, influence tabards and camp dressing.

Run after zz_rvr.sql and zz_bg_hub.sql (it replaces their gameobject war boards with NPC boards). Re-runnable.
Output: /home/claude/spp-renown/sql/zz_influence.sql
"""
import math, sys
sys.path.insert(0, '/root/wow/build')
from height import load, height

S = 533.3333333
_cache = {}
def H(m, x, y):
    f = '%03d%02d%02d' % (m, int(32 - x / S), int(32 - y / S))
    if f not in _cache:
        _cache[f] = load('/root/wow/maps/%s.map' % f)
    return height(_cache[f], x, y)

L = []; w = L.append
def esc(t): return t.replace("'", "''")

BOARD_H, BOARD_A, RALLY_A, RALLY_H = 190804, 190805, 190806, 190807
DISPLAY_A, DISPLAY_H = 17600, 17601          # Call to Arms board / War Map table (client patch)
TABARD_A, TABARD_H = 191500, 191501
GO_BANNER_A, GO_BANNER_H, GO_BRAZIER_A, GO_BONFIRE_H, GO_RACK = 190860, 190861, 190862, 190863, 190864
QUESTS = list(range(90101, 90110)) + list(range(90111, 90120))

w("-- ============================================================")
w("-- Barrens Front influence: NPC war boards (quest markers), Rally Masters, influence tabards, camp dressing")
w("-- (generated by gen_influence.py; runs after zz_rvr.sql and zz_bg_hub.sql)")
w("-- ============================================================")

# ------------------------------------------------------------------ creature templates
w(f"DELETE FROM creature_template WHERE Entry IN ({BOARD_H},{BOARD_A},{RALLY_A},{RALLY_H});")
w(f"DELETE FROM creature_questrelation WHERE id IN ({BOARD_H},{BOARD_A});")
w(f"DELETE FROM creature_involvedrelation WHERE id IN ({BOARD_H},{BOARD_A});")
def clone_ct(entry, src, sets):
    w("DROP TEMPORARY TABLE IF EXISTS tmp_ct;")
    w(f"CREATE TEMPORARY TABLE tmp_ct SELECT * FROM creature_template WHERE Entry={src};")
    w(f"UPDATE tmp_ct SET Entry={entry}, " + ", ".join(sets) + ";")
    w("INSERT INTO creature_template SELECT * FROM tmp_ct;")

board_sets = lambda name, sub, disp: [f"Name='{esc(name)}'", f"SubName='{esc(sub)}'", "MinLevel=20", "MaxLevel=20",
    f"DisplayId1={disp}", "DisplayId2=0", "DisplayId3=0", "DisplayId4=0", "DisplayIdProbability1=100", "DisplayIdProbability2=0",
    "DisplayIdProbability3=0", "DisplayIdProbability4=0", "Faction=35", "Scale=1", "CreatureType=10", "NpcFlags=2",
    "UnitFlags=770", "ExtraFlags=2", "MovementType=0", "TrainerType=0", "TrainerClass=0", "TrainerTemplateId=0",
    "GossipMenuId=0", "AIName=''", "ScriptName=''", "EquipmentTemplateId=0", "InteractionPauseTimer=0", "Civilian=1"]
clone_ct(BOARD_H, 913, board_sets('Barrens Front War Map', 'Orders of the Warchief', DISPLAY_H))
clone_ct(BOARD_A, 913, board_sets('Call to Arms', 'Orders of Theramore', DISPLAY_A))
rally_sets = lambda name: [f"Name='{esc(name)}'", "SubName='Rally Master'", "MinLevel=30", "MaxLevel=30", "NpcFlags=1",
    "UnitFlags=768", "MovementType=0", "GossipMenuId=0", "AIName=''", "ScriptName=''"]
clone_ct(RALLY_A, 68, rally_sets('Rally Master Thane'))
clone_ct(RALLY_H, 3296, rally_sets('Rally Master Grosk'))
w("DROP TEMPORARY TABLE IF EXISTS tmp_ct;")
w("INSERT INTO creature_questrelation (id,quest) VALUES " + ",".join(f"({b},{q})" for b in (BOARD_H, BOARD_A) for q in QUESTS) + ";")
w("INSERT INTO creature_involvedrelation (id,quest) VALUES " + ",".join(f"({b},{q})" for b in (BOARD_H, BOARD_A) for q in QUESTS) + ";")

w(f"DELETE FROM npc_text WHERE ID IN ({RALLY_A},{RALLY_H});")
w("INSERT INTO npc_text (ID,text0_0,text0_1,lang0,prob0) VALUES "
  f"({RALLY_A},'Every banner raised and every foe felled on the Barrens Front earns you influence with Theramore, $N. Earn enough and I will see you properly rewarded - and the finest of you will wear the Vanguard tabard.','',0,1),"
  f"({RALLY_H},'Blood spilled on the front is not forgotten, $N. Earn influence with the Warband and I will reward you - and those who prove themselves will wear the black and red.','',0,1);")

# ------------------------------------------------------------------ tabards
w(f"DELETE FROM item_template WHERE entry IN ({TABARD_A},{TABARD_H});")
for entry, name, disp, races, desc in ((TABARD_A, 'Tabard of the Barrens Vanguard', 50100, 77, 'Worn by those who held the line for Theramore on the Barrens Front.'),
                                       (TABARD_H, 'Tabard of the Barrens Warband', 50101, 178, 'Worn by those who bled the Alliance on the Barrens Front.')):
    w("DROP TEMPORARY TABLE IF EXISTS tmp_it;")
    w("CREATE TEMPORARY TABLE tmp_it SELECT * FROM item_template WHERE entry=19505;")
    w(f"UPDATE tmp_it SET entry={entry}, name='{esc(name)}', displayid={disp}, Quality=3, ItemLevel=20, RequiredLevel=0, "
      f"AllowableRace={races}, AllowableClass=-1, bonding=1, maxcount=1, BuyPrice=0, SellPrice=0, RequiredReputationFaction=0, "
      f"RequiredReputationRank=0, requiredhonorrank=0, description='{esc(desc)}';")
    w("INSERT INTO item_template SELECT * FROM tmp_it;")
w("DROP TEMPORARY TABLE IF EXISTS tmp_it;")

# ------------------------------------------------------------------ dressing objects
w(f"DELETE FROM gameobject_template WHERE entry BETWEEN {GO_BANNER_A} AND {GO_RACK};")
for entry, src, name in ((GO_BANNER_A, 178365, 'Theramore War Standard'), (GO_BANNER_H, 178364, 'Horde War Standard'),
                         (GO_BRAZIER_A, 179984, 'Brazier'), (GO_BONFIRE_H, 183909, 'Bonfire'), (GO_RACK, 105169, 'Weapon Rack')):
    w("DROP TEMPORARY TABLE IF EXISTS tmp_gt;")
    w(f"CREATE TEMPORARY TABLE tmp_gt SELECT * FROM gameobject_template WHERE entry={src};")
    w(f"UPDATE tmp_gt SET entry={entry}, name='{esc(name)}', type=5, faction=0, flags=0, data0=0, data1=0, data2=0, data3=0, data4=0, data5=0, data6=0, data7=0;")
    w("INSERT INTO gameobject_template SELECT * FROM tmp_gt;")
w("DROP TEMPORARY TABLE IF EXISTS tmp_gt;")

# ------------------------------------------------------------------ spawns
w("-- Replace the gameobject war boards (front camps and starting-zone hubs) with the NPC boards")
w("DELETE FROM gameobject WHERE guid IN (5400100,5400101) OR guid BETWEEN 5400110 AND 5400119 OR guid BETWEEN 5400120 AND 5400139;")
w("DELETE FROM creature WHERE guid BETWEEN 9100420 AND 9100439;")
creatures, gos = [], []

def rot(o): return f"0,0,{math.sin(o / 2):.6f},{math.cos(o / 2):.6f}"

# front camps: (side, board pos, faces toward, z floor)
CAMPS = [('H', -462.0, -2617.0, (-450.0, -2630.0), None), ('A', -2086.0, -3628.0, (-2093.0, -3639.0), 61.8)]
g_c, g_g = 9100420, 5400120
for side, x, y, (fx, fy), zmin in CAMPS:
    o = math.atan2(fy - y, fx - x) % (2 * math.pi)
    fwd = (math.cos(o), math.sin(o)); perp = (-fwd[1], fwd[0])
    def at(df, dp):
        px, py = x + fwd[0] * df + perp[0] * dp, y + fwd[1] * df + perp[1] * dp
        pz = H(1, px, py)
        if zmin: pz = max(pz, zmin)
        return px, py, pz
    bx, by, bz = at(0, 0)
    creatures.append(f"({g_c},{BOARD_H if side == 'H' else BOARD_A},1,1,{bx:.3f},{by:.3f},{bz + 0.05:.3f},{o:.4f},120,120,0,0) -- {side} front war board"); g_c += 1
    rx, ry, rz = at(3.0, -4.6)
    creatures.append(f"({g_c},{RALLY_H if side == 'H' else RALLY_A},1,1,{rx:.3f},{ry:.3f},{rz + 0.05:.3f},{o:.4f},120,120,0,0) -- {side} rally master"); g_c += 1
    banner = GO_BANNER_H if side == 'H' else GO_BANNER_A
    fire = GO_BONFIRE_H if side == 'H' else GO_BRAZIER_A
    for go, df, dp in ((banner, -0.8, 3.2), (banner, -0.8, -3.2), (fire, 2.5, 5.6), (GO_RACK, 0.2, -7.2)):
        px, py, pz = at(df, dp)
        gos.append(f"({g_g},{go},1,1,{px:.3f},{py:.3f},{pz:.3f},{o:.4f},{rot(o)},120,120)"); g_g += 1

# starting-zone hub boards (same spots gen_bg_hub.py used for the gameobject boards)
_AREAS = [('Northshire Valley', 0, 'A', -8949.95, -132.493, 0.0), ('Coldridge Valley', 0, 'A', -6240.32, 331.033, 6.17716),
          ('Shadowglen', 1, 'A', 10311.3, 831.463, 5.48033), ('Valley of Trials', 1, 'H', -618.518, -4251.67, 0.0),
          ('Camp Narache', 1, 'H', -2917.58, -257.98, 0.0), ('Deathknell', 0, 'H', 1664.83, 1660.14, 1.59626)]
for name, m, side, cx, cy, o in _AREAS:
    a = o + math.radians(-62); d = 7.5
    x, y = cx + d * math.cos(a), cy + d * math.sin(a)
    z = H(m, x, y)
    face = math.atan2(cy - y, cx - x) % (2 * math.pi)
    creatures.append(f"({g_c},{BOARD_H if side == 'H' else BOARD_A},{m},1,{x:.3f},{y:.3f},{z + 0.05:.3f},{face:.4f},120,120,0,0) -- {name} board"); g_c += 1

w("INSERT INTO creature (guid,id,map,spawnMask,position_x,position_y,position_z,orientation,spawntimesecsmin,spawntimesecsmax,spawndist,MovementType) VALUES")
for i, r in enumerate(creatures):
    body, c = r.split(' -- '); w(body + (";" if i == len(creatures) - 1 else ",") + " -- " + c)
w("INSERT INTO gameobject (guid,id,map,spawnMask,position_x,position_y,position_z,orientation,rotation0,rotation1,rotation2,rotation3,spawntimesecsmin,spawntimesecsmax) VALUES")
w(",\n".join(gos) + ";")
w("SELECT COUNT(*) AS influence_npcs FROM creature WHERE guid BETWEEN 9100420 AND 9100439;")

open('/home/claude/spp-renown/sql/zz_influence.sql', 'w', newline='\r\n').write("\n".join(L) + "\n")
print(len(creatures), 'creatures', len(gos), 'objects')
